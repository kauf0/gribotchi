/**
 * Паспорт изделия: весь текст руководства по эксплуатации.
 *
 * Отдельно от strings.ts, потому что это не реплики прибора, а вкладыш
 * из коробки: другой голос, другой объём, другая частота правок.
 *
 * ГЛАВНОЕ ПРАВИЛО: ни одного числа руками. Всё, что можно посчитать, считается
 * из balance.ts — иначе руководство разойдётся с игрой на первой же правке
 * баланса, а разошедшееся руководство хуже отсутствующего.
 *
 * Тон прежний: канцелярит, «объект» и «владелец», без восторгов.
 */

