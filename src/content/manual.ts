const L = B.TRAIT_LIMITS

/**
 * Сколько штаммов бывает и сколько из них берётся без обмена. Считается тем же
 * кодом, что и в реестре: числа 4060 и 2936 нельзя писать руками — добавят
 * признак, и руководство начнёт врать.
 */
const COUNTS = strainCounts(TRAIT_KEYS.map((k) => TRAITS[k].family))
const GRAFT_ONLY = COUNTS.total - COUNTS.alone

/** Сколько имён недостижимо в одиночку. Тоже считается, а не пишется. */
const NAMES_GRAFT_ONLY = NAMED.filter((n) => n.graftOnly).length

/** Игровые дни в реальные часы — их называть понятнее. */
const realHours = (days: number): number => Math.round((days * B.GAME_DAY_MS) / 3600_000)
const hours = (ms: number): number => Math.round(ms / 3600_000)
const minutes = (ms: number): number => Math.round(ms / 60_000)
/** Доля 0…1 в проценты — в тексте они читаются лучше. */
const pc = (v: number): string => `${Math.round(v * 100)}%`

/**
 * Подачи в РЕАЛЬНЫЕ сутки, а не в игровой день. Внутри игры счёт идёт
 * на игровые дни, но владельцу они ни о чём не говорят: он заходит по своим
 * суткам, и разговаривать с ним надо на его языке.
 */
const perRealDay = (perGameDay: number): number =>
  Math.round((perGameDay * 24 * 3600_000) / B.GAME_DAY_MS)

