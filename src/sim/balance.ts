/**
 * Все числа игры. В логике не должно остаться ни одной магической константы —
 * баланс крутится только здесь.
 *
 * Темп: один игровой день = три реальных часа, восемь дней в сутки.
 */

/** Длительность игрового дня в реальных миллисекундах. */
export const GAME_DAY_MS = 3 * 60 * 60 * 1000

/**
 * Шаг симуляции в реальных миллисекундах. Оффлайн-догон идёт такими же шагами,
 * что и живая игра, — иначе состояние после возвращения расходилось бы с тем,
 * что получилось бы при непрерывной игре. Минута даёт 43 200 шагов на месяц
 * отсутствия: считается мгновенно.
 */
export const STEP_MS = 60 * 1000

