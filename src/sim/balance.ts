/**
 * Плесень — она же здоровье: mold >= 1 означает смерть. Медленно копится всегда
 * (за этим и нужна кнопка МЫТЬ) и резко ускоряется на голоде. От пустого бака
 * до гибели — примерно 4 игровых дня, то есть сутки реального невнимания.
 */
export const MOLD_PER_DAY = 0.02
export const MOLD_STARVING_PER_DAY = 0.25
export const STARVING_BELOW = 0.1

/**
 * Обида. Растёт быстро, убывает медленно и только при исправном уходе —
 * в этой асимметрии весь смысл: сытость возвращается одним нажатием, лицо нет.
 *
 * Копиться начинает ещё на подходе к нулю, а не после него. Иначе обида
 * отставала бы от плесени и гриб успевал бы умереть почти сразу после того,
 * как отвернулся: главный кадр игры мелькал бы пять часов из суток. С этими
 * числами объект отворачивается примерно через 15 реальных часов забвения
 * и живёт после этого ещё около шести — окно, в которое игрок успевает
 * вернуться и извиниться.
 */
export const RESENT_PER_DAY = 0.3
export const RESENT_DECAY_PER_DAY = 0.1
export const RESENT_TRIGGER_FOOD = 0.25
export const RESENT_TRIGGER_MOLD = 0.6
export const RESENT_DECAY_MIN_FOOD = 0.6
export const RESENT_DECAY_MAX_MOLD = 0.2

